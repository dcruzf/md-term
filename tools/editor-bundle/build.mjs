// Rebuilds the vendored editor bundle:  npm install && npm run build
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const here = (path) => fileURLToPath(new URL(path, import.meta.url));
const out = "../../src/md_term/assets/js/vendor/";

await build({
  entryPoints: [here("entry.js")],
  outfile: here(`${out}codemirror.js`),
  bundle: true,
  format: "esm",
  platform: "browser",
  minify: true,
  legalComments: "inline",
});

const { devDependencies } = JSON.parse(readFileSync(here("package.json"), "utf8"));
const rows = Object.entries(devDependencies)
  .filter(([name]) => name !== "esbuild")
  .map(([name, version]) => `| \`${name}\` | ${version} | MIT |`);
writeFileSync(
  here(`${out}NOTICE.md`),
  `# Third-party code in this directory

\`codemirror.js\` is a bundle generated by \`tools/editor-bundle\` from these
packages, all by Marijn Haverbeke and contributors:

| Package | Version | License |
| ------- | ------- | ------- |
${rows.join("\n")}
`,
);
console.log(`editor bundle written to ${out}`);
